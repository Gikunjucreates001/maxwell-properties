-- The API uses a server-only Postgres connection. Block direct Data API access
-- until explicit, user-scoped Supabase Auth policies are added for any client.
do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'users', 'properties', 'units', 'tenants', 'payments', 'issues',
    'expenses', 'approval_requests', 'approval_comments', 'notification_jobs'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all on table public.%I from anon, authenticated', table_name);
  end loop;
end;
$$;

